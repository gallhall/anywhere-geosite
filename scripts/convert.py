#!/usr/bin/env python3
"""Convert v2fly/domain-list-community categories to Anywhere .arrs.

Supported: suffix domain, keyword. Unsupported: exact (full), regexp.
"""
import argparse
import json
from pathlib import Path

TARGETS = {
    "force-proxy": (["google", "microsoft", "oracle"], 0),
    "cn": (["cn"], 1),
    "private": (["private"], 1),
    "steam-cn": (["steam@cn"], 1),
    "ads": (["category-ads-all"], 2),
    "stun": (["category-stun"], 2),
}

def collect(name, root, skipped, stack=(), filters=()):
    name = name.lower()
    if name in stack:
        raise ValueError("Cyclic include: " + " > ".join((*stack, name)))
    path = root / name
    if not path.is_file():
        raise FileNotFoundError(f"GeoSite category missing: {name}")
    found = set()
    for lineno, original in enumerate(path.read_text(encoding="utf8").splitlines(), 1):
        line = original.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        head = parts[0]
        attrs = {p[1:].lower() for p in parts[1:] if p.startswith("@")}
        kind, sep, value = head.partition(":")
        if not sep:
            kind, value = "domain", head
        if kind == "include":
            selectors = tuple(p[1:].lower() for p in parts[1:] if p.startswith("@"))
            found.update(collect(value, root, skipped, (*stack, name), (*filters, *selectors)))
            continue
        if any((f[1:] in attrs if f.startswith("-") else f not in attrs) for f in filters):
            continue
        value = value.lower().strip(".")
        if kind in ("domain", "keyword") and value:
            found.add((2 if kind == "domain" else 3, value))
        else:
            skipped.append({"file": name, "line": lineno, "type": kind, "value": value})
    return found

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=Path("rules"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    report = {"source": "v2fly/domain-list-community", "categories": {}, "skipped": []}
    for target, (categories, action) in TARGETS.items():
        rules = set()
        for entry in categories:
            name, sep, attribute = entry.partition("@")
            selected = collect(name, args.source, report["skipped"], filters=(attribute,) if sep else ())
            if not selected:
                raise ValueError(f"GeoSite category {entry} generated zero rules")
            report["categories"][entry] = len(selected)
            rules.update(selected)
        if not 0 < len(rules) <= 100000:
            raise ValueError(f"{target}: invalid Anywhere rule count {len(rules)}")
        lines = [
            f"name = GeoSite {target}",
            f"routing = {action}",
            "",
            "# Generated by GitHub Actions. Assign force-proxy to PROXY in Anywhere.",
        ]
        lines.extend(f"{kind}, {value}" for kind, value in sorted(rules))
        (args.output / f"{target}.arrs").write_text("\n".join(lines) + "\n", encoding="utf8")
        print(f"{target}: {len(rules)} rules")
    (args.output / "conversion-report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf8"
    )
    print(f"Skipped unsupported entries: {len(report['skipped'])}")

if __name__ == "__main__":
    main()
